import 'dart:convert';

/// A remote subscription for the independent Mihomo client. It is kept in its own
/// SharedPreferences key, so adding or removing it never touches the main VPN profile.
class MihomoSubscription {
  final String id;
  final String name;
  final String url;

  const MihomoSubscription({
    required this.id,
    required this.name,
    required this.url,
  });

  factory MihomoSubscription.fromJson(Map<String, dynamic> json) =>
      MihomoSubscription(
        id: json['id'] as String? ?? '',
        name: json['name'] as String? ?? 'Subscription',
        url: json['url'] as String? ?? '',
      );

  Map<String, dynamic> toJson() => {'id': id, 'name': name, 'url': url};

  static List<MihomoSubscription> decodeList(String? raw) {
    if (raw == null || raw.isEmpty) return const [];
    try {
      final decoded = jsonDecode(raw);
      if (decoded is! List) return const [];
      return decoded
          .whereType<Map>()
          .map((item) => MihomoSubscription.fromJson(item.cast<String, dynamic>()))
          .where((item) => item.url.isNotEmpty)
          .toList(growable: false);
    } catch (_) {
      return const [];
    }
  }

  static String encodeList(List<MihomoSubscription> items) =>
      jsonEncode([for (final item in items) item.toJson()]);
}

/// Builds a complete mihomo config. Mihomo itself understands YAML, URI lists and
/// base64 subscriptions, so every provider is fetched by the core via HTTP and no
/// subscription parser is needed in Dart.
class MihomoConfigBuilder {
  static const groupName = 'MILI';
  static const testUrl = 'https://www.gstatic.com/generate_204';

  static String build(List<MihomoSubscription> subscriptions) {
    final providers = StringBuffer();
    final uses = StringBuffer();

    for (var i = 0; i < subscriptions.length; i++) {
      final provider = 'look_$i';
      uses.writeln('      - $provider');
      providers
        ..writeln('  $provider:')
        ..writeln('    type: http')
        ..writeln('    url: ${_yaml(subscriptions[i].url)}')
        ..writeln('    path: ./providers/$provider.yaml')
        ..writeln('    interval: 86400')
        ..writeln('    health-check:')
        ..writeln('      enable: true')
        ..writeln('      url: ${_yaml(testUrl)}')
        ..writeln('      interval: 300')
        ..writeln('      timeout: 5000');
    }

    return '''
# Generated by LookVPN for the independent Mihomo tab.
mixed-port: 7892
allow-lan: false
mode: rule
log-level: warning
ipv6: true
unified-delay: true
tcp-concurrent: true
profile:
  store-selected: true

dns:
  enable: true
  ipv6: true
  nameserver:
    - 1.1.1.1
    - 8.8.8.8
  fallback:
    - https://1.1.1.1/dns-query
    - https://8.8.8.8/dns-query

proxy-providers:
$providers
proxy-groups:
  - name: $groupName
    type: select
    proxies:
      - DIRECT
    use:
$uses
rules:
  - MATCH,$groupName
''';
  }

  /// JSON-style double quoting is valid YAML and protects URLs containing `#`, `:` etc.
  static String _yaml(String value) => jsonEncode(value);
}
